from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(..., description="List of messages to be processed by the agent")
    user_question: Annotated[list, add] = Field(..., description="Original question asked by the user")
    curated_ques: str = Field(..., description="Curated user question to be answered by the agent")
    prompt_query_context: str = Field(..., description="A detailed prompt with the SQL DB context that will help agent to generate SQL query")
    generated_sql_query: str = Field(..., description='The SQL query generated by the agent based on the curated question and prompt context')
    is_safe: Literal["Yes", "No"] = Field(..., description='Indicates wheather generated SQL query is safe to execute or not')
    comments: str = Field(..., description="Comments from the judge regarding the SQL query")
    sql_query_execution_result: str = Field(..., description="The result of executing the generated SQL query on the database")
    final_answer: str = Field(..., description="The final answer generate by the agent based on the SQL query")

class JudgeSchema(BaseModel):
    answer : Literal["Yes","No"] = Field(..., description="Indicates whether the generated SQL query is safe to execute or not")
    comments : str = Field(..., description="Additional comments or feedback from the judge regarding the SQL query")